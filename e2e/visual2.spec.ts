import { test } from '@playwright/test';
import { freshApp } from './helpers';
const out = process.env.SHOTS ?? '/tmp';
test('visual check 2', async ({ page, context }) => {
  test.skip(!process.env.SHOTS, 'manual visual check only');
  await freshApp(page);
  await page.screenshot({ path: `${out}/hero.png` });
  await page.getByTestId('build-demo-hero').click();
  await page.waitForURL(/\/quizzes\//);
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${out}/roundbuilder.png` });
  const hostP = context.waitForEvent('page');
  await page.getByTestId('start-presentation').click();
  const host = await hostP;
  await host.setViewportSize({ width: 1600, height: 950 });
  const audP = context.waitForEvent('page');
  await host.getByTestId('open-audience').click();
  const aud = await audP;
  await aud.setViewportSize({ width: 1280, height: 720 });
  for (const t of ['Owls', 'Foxes', 'Bears', 'Quizzly Bears']) { await host.getByTestId('new-team').fill(t); await host.getByTestId('add-team').click(); }
  await host.getByTestId('next-action').click();
  await host.getByTestId('toggle-timer').click();
  await host.waitForTimeout(2500);
  await aud.screenshot({ path: `${out}/aud-question.png` });
  await host.getByRole('button', { name: 'Mark Foxes correct' }).click();
  await host.getByRole('button', { name: 'Mark Owls correct' }).click();
  await host.getByTestId('answer-check').fill('Germny');
  await host.screenshot({ path: `${out}/host.png` });
  await host.getByTestId('toggle-leaderboard').click();
  await aud.waitForTimeout(1200);
  await aud.screenshot({ path: `${out}/aud-leaderboard.png` });
  await host.getByTestId('end-presentation').click();
  await aud.waitForTimeout(1800);
  await aud.screenshot({ path: `${out}/aud-podium.png` });
  await page.keyboard.press('Control+k');
  await page.getByTestId('command-input').fill('fla');
  await page.waitForTimeout(300);
  await page.screenshot({ path: `${out}/palette.png` });
});
